// Site generator. Run: npm run build   (node tools/build.mjs)
// Renders every page as static HTML (English pre-rendered, French swapped in by js/i18n.js).
// Structure: tools/lib/data.mjs (content + i18n), tools/lib/layout.mjs (chrome), tools/lib/pages/*.mjs (one per page).
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { ROOT, SITE, PROJECTS, fr, en } from "./lib/data.mjs";
import * as home from "./lib/pages/home.mjs";
import * as hd from "./lib/pages/heroes-dawn.mjs";
import * as portfolio from "./lib/pages/portfolio.mjs";
import * as studio from "./lib/pages/studio.mjs";
import * as hr from "./lib/pages/hell-rising.mjs";
import * as contact from "./lib/pages/contact.mjs";
import * as project from "./lib/pages/project.mjs";

const out = (file, html) => writeFileSync(join(ROOT, file), html);

out("js/i18n-data.js", `/* Generated by tools/build.mjs from i18n/*.json — do not edit */\nwindow.N29_I18N = ${JSON.stringify({ fr, en })};\n`);
mkdirSync(join(ROOT, "projects"), { recursive: true });

out("index.html", home.render());
out("heroes-dawn.html", hd.render());
out("portfolio.html", portfolio.render());
out("studio.html", studio.render());
out("hell-rising.html", hr.render());
out("contact.html", contact.render());
const subpages = PROJECTS.filter((p) => !p.href);
subpages.forEach((p) => out(`projects/${p.slug}.html`, project.render(p)));
out("projects/heroes-dawn.html", project.redirect());

const urls = ["", "heroes-dawn.html", "portfolio.html", "studio.html", "hell-rising.html", "contact.html", ...subpages.map((p) => `projects/${p.slug}.html`)];
out("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((u) => `  <url><loc>${SITE}/${u}</loc></url>`).join("\n")}\n</urlset>\n`);
out("robots.txt", `User-agent: *\nAllow: /\nSitemap: ${SITE}/sitemap.xml\n`);
console.log(`Built 6 pages + ${subpages.length} project pages.`);
